#!/usr/bin/env python3
"""
Builds src/world/data/realSites.ts from two public elevation models.

  Moon  LRO-LOLA 5 m/px south-pole DEM, Site04 "Shackleton rim"
        https://pgda.gsfc.nasa.gov/products/78
        Barker, M.K., et al. (2021), Improved LOLA Elevation Maps for South Pole Landing
        Sites, Planetary & Space Science 203, 105119, doi:10.1016/j.pss.2020.105119
  Mars  Mars 2020 Terrain Relative Navigation CTX DTM mosaic, 20 m/px, Jezero crater
        https://doi.org/10.5066/P906QQT8 (USGS Astrogeology; Fergason et al., 2020)

Each site becomes a 384 x 384 grid covering 6.4 km, heights relative to the centre, stored
as 16-bit integers, row-delta coded and gzip-compressed, then base64. Usage:

  pip install pillow numpy
  curl -LO https://pgda.gsfc.nasa.gov/data/LOLA_5mpp/Site04/Site04_final_adj_5mpp_surf.tif
  curl -LO https://planetarymaps.usgs.gov/mosaic/mars2020_trn/CTX/JEZ_ctx_B_soc_008_DTM_MOLAtopography_DeltaGeoid_20m_Eqc_latTs0_lon0.tif
  python3 scripts/real-terrain.py <folder with both .tif> src/world/data/realSites.ts
"""
import base64, gzip, math, sys
import numpy as np
from PIL import Image

Image.MAX_IMAGE_PIXELS = None
SIZE = 384
EXTENT = 6400.0


def window(path, row, col, metres_per_px):
    dem = Image.open(path)
    half = int(round(EXTENT / 2 / metres_per_px))
    box = (col - half, row - half, col + half, row + half)
    tile = dem.crop(box).resize((SIZE, SIZE), Image.LANCZOS)
    a = np.array(tile, dtype=np.float64)
    centre = float(np.array(dem.crop((col - 1, row - 1, col + 1, row + 1))).mean())
    return a - centre, centre


def pack(a, scale):
    q = np.round(a / scale)
    assert np.abs(q).max() < 32767, np.abs(q).max()
    q = q.astype(np.int16)
    delta = q.copy()
    delta[:, 1:] = q[:, 1:] - q[:, :-1]
    return base64.b64encode(gzip.compress(delta.astype('<i2').tobytes(), 9, mtime=0)).decode()


def main(folder, out):
    # Moon: the flattest high spot of the rim crest with the crater wall within reach
    # (found by a search over the tile: 20 m cell 360, 313 -> 5 m pixel 1442, 1254).
    moon, moon_centre = window(f'{folder}/Site04_final_adj_5mpp_surf.tif', 1442, 1254, 5.0)
    # Mars: Octavia E. Butler Landing, where Perseverance touched down (18.4447 N, 77.4508 E).
    R = 3396190.0
    ulx, uly = 4573663.250853, 1109693.140188
    col = int(round((R * math.radians(77.4508) - ulx) / 20.0))
    row = int(round((uly - R * math.radians(18.4447)) / 20.0))
    mars, mars_centre = window(f'{folder}/JEZ_ctx_B_soc_008_DTM_MOLAtopography_DeltaGeoid_20m_Eqc_latTs0_lon0.tif', row, col, 20.0)
    sites = [
        ('SHACKLETON', moon, 0.1, moon_centre, 'LRO-LOLA 5 m/px, Site04 Shackleton rim (Barker et al., 2021)'),
        ('JEZERO', mars, 0.02, mars_centre, 'Mars 2020 TRN CTX DTM mosaic 20 m/px (USGS Astrogeology; Fergason et al., 2020)'),
    ]
    with open(out, 'w') as f:
        f.write('/* Generated by scripts/real-terrain.py from public NASA / USGS elevation models. Do not edit by hand. */\n\n')
        f.write('export interface RealSite {\n  /** Samples per side. */\n  size: number;\n  /** Metres covered per side. */\n  extent: number;\n  /** Metres per stored unit. */\n  scale: number;\n  /** Elevation of the centre in the source model, m. */\n  datum: number;\n  source: string;\n  /** gzip of row-delta-coded little-endian int16 heights, base64. */\n  data: string;\n}\n\n')
        for name, a, scale, centre, source in sites:
            print(name, 'relief', round(a.min(), 1), round(a.max(), 1), 'centre', round(centre, 1))
            f.write(f"export const {name}: RealSite = {{\n  size: {SIZE},\n  extent: {int(EXTENT)},\n  scale: {scale},\n  datum: {centre:.1f},\n  source: '{source}',\n  data: '{pack(a, scale)}',\n}};\n\n")


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
